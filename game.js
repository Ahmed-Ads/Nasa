  function updateAstronaut(dt) {
    if (!state.level || state.screen !== 'game') return;
    let dx = (keys.right ? 1 : 0) - (keys.left ? 1 : 0);
    let dy = (keys.down ? 1 : 0) - (keys.up ? 1 : 0);
    if (dx || dy) {
      astro.target = null;
      const len = Math.hypot(dx, dy);
      dx /= len; dy /= len;
    } else if (astro.target) {
      const tx = astro.target.x - astro.x;
      const ty = astro.target.y - astro.y;
      const d = Math.hypot(tx, ty);
      if (d < 4 * U) astro.target = null;
      else { dx = tx / d; dy = ty / d; }
    }
    astro.moving = !!(dx || dy);
    if (astro.moving) {
      astro.x = clamp(astro.x + dx * 46 * U * dt);
      astro.y += dy * 46 * U * dt;
      if (Math.abs(dx) > 0.1) astro.facing = dx > 0 ? 1 : -1;

      astro.x = Math.max(14 * U, Math.min(W - 14 * U, astro.x));
      astro.y = Math.max(H * 0.24, Math.min(H - 8 * U, astro.y));

      const ddx = astro.x - layout.base.x;
      const ddy = astro.y - (layout.base.y + baseR * 0.15);
      const nrx = baseR * 1.15;
      const nry = baseR * 0.6;
      const norm = (ddx * ddx) / (nrx * nrx) + (ddy * ddy) / (nry * nry);
      if (norm < 1 && norm > 0.0001) {
        const push = 1 / Math.sqrt(norm);
        astro.x = layout.base.x + ddx * push;
        astro.y = layout.base.y + baseR * 0.15 + ddy * push;
      }

      const prev = Math.floor(astro.walkTime / 0.16);
      astro.walkTime += dt;
      if (Math.floor(astro.walkTime / 0.16) !== prev) {
        dustPuffs.push({ x: astro.x - astro.facing * 2 * U, y: astro.y, life: 0.4 });
        if (dustPuffs.length > 14) dustPuffs.shift();
      }
    }
    for (let i = dustPuffs.length - 1; i >= 0; i--) {
      dustPuffs[i].life -= dt;
      if (dustPuffs[i].life <= 0) dustPuffs.splice(i, 1);
    }
  }

