  function splitBudget(rows, budget) {
    const out = {};
    const base = Math.floor(budget / rows.length);
    let extra = budget - base * rows.length;
    for (const row of rows) {
      out[row] = base + (extra > 0 ? 1 : 0);
      if (extra > 0) extra -= 1;
    }
    return out;
  }

