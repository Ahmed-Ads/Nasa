  function drawAsset(key, cx, by, maxW, maxH, opts = {}) {
    const a = SPR[key];
    if (!a || !a.ok) return false;
    const ratio = a.img.width / a.img.height;
    let w = maxW;
    let h = w / ratio;
    if (h > maxH) { h = maxH; w = h * ratio; }
    ctx.save();
    if (opts.flip) {
      ctx.translate(Math.round(cx), 0);
      ctx.scale(-1, 1);
      ctx.translate(-Math.round(cx), 0);
    }
    ctx.imageSmoothingEnabled = true;
    ctx.imageSmoothingQuality = 'high';
    ctx.globalAlpha = opts.alpha ?? 1;
    const x = Math.round(cx - w / 2);
    const y = Math.round(by - h + (opts.dy || 0));
    if (opts.rotate) {
      ctx.translate(x + w / 2, y + h / 2);
      ctx.rotate(opts.rotate);
      ctx.drawImage(a.img, -w / 2, -h / 2, w, h);
    } else {
      ctx.drawImage(a.img, x, y, Math.round(w), Math.round(h));
    }
    ctx.restore();
    ctx.imageSmoothingEnabled = false;
    return true;
  }

