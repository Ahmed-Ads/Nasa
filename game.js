  function drawAstronaut(time) {
    const spriteKey = state.levelId === '1.2' ? 'crew/wrench' : 'crew/walk';
    const w = 30 * U;
    const h = 56 * U;
    const bob = reduceMotion ? 0 : astro.moving ? Math.round(Math.sin(astro.walkTime * 12)) : Math.round(Math.sin(time * 2.2));
    const jump = state.phase === 'win' && !reduceMotion ? Math.abs(Math.sin(time * 3)) * 4 * U : 0;

    for (const puff of dustPuffs) {
      ctx.globalAlpha = Math.max(0, puff.life * 1.4);
      px(puff.x - 1, puff.y - 1, 3, 2, '#9ea5b8');
    }
    ctx.globalAlpha = 1;

    if (astro.target && state.phase !== 'over') {
      ctx.globalAlpha = 0.5 + 0.3 * Math.sin(time * 6);
      px(astro.target.x - 2, astro.target.y - 1, 4, 2, '#7ce3ff');
      ctx.globalAlpha = 1;
    }

    ellipse(astro.x, astro.y + 1, w * 0.32, 3.5 * U, 'rgba(10,12,20,.5)');

    const usedSprite = drawAsset(spriteKey, astro.x, astro.y + bob - jump, w, h, {
      flip: astro.facing < 0,
      dy: 0,
    });

    if (!usedSprite) {
      const scale = Math.max(1, Math.round(2 * U));
      const rows = ASTRO;
      const sw = rows[0].length * scale;
      const sh = rows.length * scale;
      drawSpriteRows(rows, astro.x - sw / 2, astro.y - sh + bob - jump, scale, astro.facing < 0);
    }
  }

