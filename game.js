  function buildTerrainCache(rnd) {
    terrainCanvas = document.createElement('canvas');
    terrainCanvas.width = W;
    terrainCanvas.height = H;
    const t = terrainCanvas.getContext('2d');
    t.imageSmoothingEnabled = false;

    // horizon
    const horizon = [];
    for (let x = 0; x <= W; x += 6) {
      let y = H * 0.05;
      if (x > W * 0.72) y += ((x - W * 0.72) / (W * 0.28)) * H * 0.1;
      if (x > W * 0.86) y += ((x - W * 0.86) / (W * 0.14)) * H * 0.2;
      y += Math.round((rnd() - 0.5) * 4);
      horizon.push([x, Math.max(4, Math.round(y))]);
    }

    // cliff between pale regolith and dark basalt
    const cliff = [
      [W * 0.33, 0], [W * 0.36, H * 0.11], [W * 0.58, H * 0.13],
      [W * 0.61, H * 0.3], [W * 0.32, H * 0.33], [W * 0.29, H * 0.62],
      [W * 0.26, H * 0.85], [W * 0.24, H],
    ];
    const ridge = [];
    for (let i = 0; i < cliff.length - 1; i++) {
      const [x1, y1] = cliff[i];
      const [x2, y2] = cliff[i + 1];
      const steps = Math.max(3, Math.round(Math.hypot(x2 - x1, y2 - y1) / 8));
      for (let s = 0; s < steps; s++) {
        const k = s / steps;
        ridge.push([
          Math.round(x1 + (x2 - x1) * k + (rnd() - 0.5) * 5),
          Math.round(y1 + (y2 - y1) * k + (rnd() - 0.5) * 3),
        ]);
      }
    }
    ridge.push(cliff[cliff.length - 1]);

    t.save();
    t.beginPath();
    t.moveTo(0, horizon[0][1]);
    for (const [hx, hy] of horizon) t.lineTo(hx, hy);
    t.lineTo(W, H); t.lineTo(0, H); t.closePath();
    t.clip();

    t.fillStyle = '#292e3e';
    t.fillRect(0, 0, W, H);
    for (let y = 0; y < H; y += 3) {
      for (let x = 0; x < W; x += 3) {
        const n = rnd();
        if (n < 0.2) t.fillStyle = '#222634';
        else if (n < 0.34) t.fillStyle = '#33394c';
        else if (n > 0.985) t.fillStyle = '#474f66';
        else continue;
        t.fillRect(x, y, 3, 2);
      }
    }

    // cliff face
    const cliffH = Math.round(30 * U);
    t.fillStyle = '#1b1f2d';
    t.beginPath();
    t.moveTo(ridge[0][0], ridge[0][1]);
    for (const [rx, ry] of ridge) t.lineTo(rx, ry);
    for (let i = ridge.length - 1; i >= 0; i--) t.lineTo(ridge[i][0], ridge[i][1] + cliffH);
    t.closePath();
    t.fill();

    for (let i = 0; i < ridge.length; i++) {
      const [rx, ry] = ridge[i];
      if (ry < H * 0.12 || ry > H * 0.7) continue;
      t.fillStyle = i % 2 ? '#2b3145' : '#131622';
      t.fillRect(rx, ry + 2, 2, Math.round(cliffH * (0.5 + rnd() * 0.5)));
    }

    // pale plateau
    t.save();
    t.beginPath();
    t.moveTo(0, 0);
    t.lineTo(ridge[0][0], 0);
    for (const [rx, ry] of ridge) t.lineTo(rx, ry);
    t.lineTo(0, H);
    t.closePath();
    t.clip();
    t.fillStyle = '#7c8296';
    t.fillRect(0, 0, W, H);
    for (let y = 0; y < H; y += 3) {
      for (let x = 0; x < W; x += 3) {
        const n = rnd();
        if (n < 0.22) t.fillStyle = '#8b92a6';
        else if (n < 0.38) t.fillStyle = '#6c7285';
        else if (n > 0.985) t.fillStyle = '#a2a9bd';
        else continue;
        t.fillRect(x, y, 3, 2);
      }
    }
    t.restore();

    // rim
    t.strokeStyle = '#101420';
    t.lineWidth = 2;
    t.beginPath();
    t.moveTo(ridge[0][0], ridge[0][1]);
    for (const [rx, ry] of ridge) t.lineTo(rx, ry);
    t.stroke();

    // cave mouth
    drawCave(t, layout.cave.x, layout.cave.y, 20 * U);

    // craters
    for (const c of craters) drawCrater(t, c);

    t.strokeStyle = '#121624';
    t.lineWidth = 2;
    t.beginPath();
    t.moveTo(horizon[0][0], horizon[0][1]);
    for (const [hx, hy] of horizon) t.lineTo(hx, hy);
    t.stroke();

    t.restore();
  }

